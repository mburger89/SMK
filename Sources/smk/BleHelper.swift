// ESP32-C6 BLE HID glue — full Swift port of the former
// Sources/components/ble_helper.c (now deleted).
//
// The final round of this port moved the struct construction over too:
// Bridging.h imports host/ble_hs.h, host/ble_hs_mbuf.h, services/gap/
// ble_svc_gap.h, nimble/nimble_port.h, nvs_flash.h and smk_ble_uuids.h, so
// `struct ble_hs_adv_fields` and the global `struct ble_hs_cfg` — both
// genuinely bitfield-heavy — come across as real ClangImporter types whose
// bitfield members are computed properties with header-derived packing, and
// the GATT service/characteristic definition tables are built from the
// imported `ble_gatt_svc_def`/`ble_gatt_chr_def` types. Nothing here
// mirrors a layout by hand. Same for esp_hid_device_config_t/
// esp_hid_raw_report_map_t (esp_hidd.h, imported all along).
//
// Keymap upload rides a custom GATT service (write characteristic in,
// notify characteristic back), NOT a HID Report ID 2 channel — macOS hides
// the HID service (0x1812) from Core Bluetooth apps entirely, so a HID
// vendor report was unreachable from the configurator. See
// smk_configurator/docs/superpowers/specs/2026-08-15-ble-custom-gatt-upload-design.md
// and Sources/components/smk_ble_uuids.h (generated by
// generate_ble_uuids.sh) for the three UUIDs.
//
// Buffer lifetimes: esp_hidd_dev_init(), NimBLE's GATT registration, and
// the advertiser keep pointers into the report map, the name strings, the
// UUIDs, and the service-definition tables past the call, so all of those
// live in permanently-allocated storage (deliberate leak, matching the C
// original's `static const` arrays) — same pattern as
// ports/common/BleHidGatt.swift's permanentCopy.
//
// hidDev ownership: init_ble_hid() below receives esp_hidd_dev_init()'s
// out-param directly into `hidDev`, the single source of truth every other
// function here reads.

